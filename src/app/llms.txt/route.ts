// Описание сайта для систем AI-поиска в формате llmstxt.org.
// Текст меняется вручную: это заявление о том, чем занимается организация,
// и оно не должно расходиться с сайтом. Адреса и география подставляются по
// домену захода (мультидомен) — AI-поиск в РК/РФ видит свой домен.
import { currentSite, siteOrigin, DEFAULT_SITE } from "@/lib/seo/site";
import { getLocale } from "@/i18n/server";

const content = (origin: string, country: string) => `# Бизнес-платформа ACTIVE SALES

> Онлайн-платформа с курсами по техникам продаж и AI-наставником для тех, кто хочет освоить и прокачать техники продаж.

Платформа предлагает онлайн-курсы по техникам продаж: видеоуроки с AI-тренажёром, тесты и сертификацию. Обучение проходит в удобном онлайн-формате с поддержкой AI-наставника. Подходит для менеджеров по продажам, предпринимателей и всех, кто развивает навыки продаж.

## Основные разделы
- [Курсы по продажам с AI-наставником](${origin}): главная страница платформы с обзором обучения и AI-наставника
- [Каталог курсов по продажам](${origin}/courses): список доступных онлайн-курсов по продажам
- [Публичная оферта](${origin}/offer): условия предоставления услуг платформы
- [Оферта для организаций](${origin}/offer-b2b): корпоративный доступ, места в лицензии, обезличивание сотрудников
- [Политика конфиденциальности](${origin}/privacy): порядок обработки персональных данных

## Факты
- Услуги: онлайн-курсы по техникам продаж, видеоуроки с AI-тренажёром, тесты и сертификация
- Формат: онлайн-обучение с AI-наставником
- География: ${country}
- Телефон: +375 (29) 605-30-32
- Сайт: ${origin}

## Контакты
- Телефон: +375 (29) 605-30-32
- Сайт: ${origin}
`;

export async function GET() {
    const [origin, site, locale] = await Promise.all([siteOrigin(), currentSite(), getLocale()]);
    // Страна — на языке страницы: на /uz описание для AI-поиска тоже узбекское.
    const country = (site ?? DEFAULT_SITE).country;
    return new Response(content(origin, country[locale]), {
        headers: {
            'Content-Type': 'text/plain; charset=utf-8',
            'Cache-Control': 'public, max-age=3600',
        },
    });
}
