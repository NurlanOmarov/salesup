/**
 * Версия редакции, которую акцептовал человек: у страновых редакций свой суффикс,
 * иначе по User.termsVersion нельзя понять, какой текст ему показывали.
 */
export function legalVersion(country: LegalCountry): string {
  return country === "BY" ? LEGAL_VERSION : `${LEGAL_VERSION}-${country}`;
}

/** Приложение к оферте для физических лиц. Для BY — пусто (основной текст и есть BY). */
export function offerSupplement(country: LegalCountry, domain: string): string {
  if (country === "BY") return "";
  const c = PROFILES[country];
  return `

## Приложение. Особые условия для Заказчиков из ${c.nameGenitive}

Приложение применяется, если Заказчик — физическое лицо, находящееся ${c.inCountry}, и (или) договор заключён через доменное имя ${domain}. В остальном действует основной текст Оферты.

П1. Исполнитель — ${REQUISITES.shortName}, зарегистрированный в Республике Беларусь; услуги оказываются дистанционно средствами Платформы. Договор регулируется правом Республики Беларусь. Это не лишает Заказчика-потребителя прав, предоставленных ему императивными нормами ${c.consumerLaw}, от которых стороны не вправе отступить соглашением.

П2. Стоимость доступа установлена в белорусских рублях (BYN). На витрине дополнительно показывается справочный эквивалент в ${c.currency} по официальному курсу Национального банка Республики Казахстан на дату отображения; такой эквивалент носит информационный характер и не является ценой договора. Сумма к оплате определяется в белорусских рублях либо в валюте выставленного счёта. Комиссии банков и платёжных посредников Заказчика в стоимость услуг не входят и Исполнителем не возмещаются.

П3. Персональные данные Заказчика обрабатываются в соответствии с Политикой (${domain}/privacy) и Законом Республики Беларусь от 7 мая 2021 г. № 99-З «О защите персональных данных» с учётом ${c.dataLaw}. Обработка и хранение осуществляются на серверах, расположенных в Республике Беларусь. Акцептуя Оферту, Заказчик даёт согласие на трансграничную передачу своих персональных данных в Республику Беларусь и вправе отозвать это согласие в порядке, предусмотренном Политикой.

П4. Обращения, претензии и заявления направляются на ${REQUISITES.email} и рассматриваются в сроки, установленные основным текстом Оферты, а если ${c.lawOf} устанавливает для потребителя более короткий срок — в такой срок. Заказчик-потребитель вправе обратиться в ${c.regulator}.

П5. Объём услуги, порядок предоставления доступа, права на материалы, порядок отказа от договора и возврата оплаты одинаковы для всех Заказчиков независимо от домена, через который заключён договор.`;
}

/** Приложение к оферте для организаций. */
export function offerB2bSupplement(country: LegalCountry, domain: string): string {
  if (country === "BY") return "";
  const c = PROFILES[country];
  return `

## Приложение 2. Особые условия для Заказчиков, зарегистрированных ${c.inCountry}

Приложение применяется, если Заказчик — юридическое лицо или индивидуальный предприниматель, зарегистрированный ${c.inCountry}, и (или) договор заключён через доменное имя ${domain}.

Б1. Исполнитель — ${REQUISITES.shortName} (Республика Беларусь). Договор регулируется правом Республики Беларусь; спор, не урегулированный в претензионном порядке, рассматривается по месту нахождения Исполнителя, если стороны письменно не согласовали иное.

Б2. Расчёты производятся в белорусских рублях либо в валюте выставленного счёта. Налоги и сборы, обязанность по уплате или удержанию которых возникает у Заказчика по ${c.lawOf} (включая обязанности налогового агента), исполняются Заказчиком самостоятельно и в стоимость услуг не включаются.

Б3. Персональные данные Работников Заказчика Платформа не получает: учётные записи создаются самозаписью по коду, без фамилии, имени, адреса электронной почты и телефона (раздел 10 и Приложение 1 основного текста). Оператором персональных данных Работников остаётся Заказчик; ${c.dataLaw} применяется к Заказчику как к оператору.

Б4. Обезличенные сведения об обучении (псевдоним, прогресс, результаты тестов) обрабатываются и хранятся на серверах в Республике Беларусь. Заказчик самостоятельно уведомляет Работников об использовании Платформы в объёме, требуемом ${c.lawOf}.

Б5. Закрывающие документы оформляются актом в порядке раздела 6 основного текста; по запросу Заказчика Исполнитель предоставляет документы, необходимые для бухгалтерского учёта в стране регистрации Заказчика, если их оформление не противоречит законодательству Республики Беларусь.`;
}

/** Приложение к политике обработки персональных данных. */
export function privacySupplement(country: LegalCountry, domain: string): string {
  if (country === "BY") return "";
  const c = PROFILES[country];
  return `

## Приложение. Обработка данных лиц, находящихся ${c.inCountry}

Д1. Приложение применяется к субъектам персональных данных, находящимся ${c.inCountry}, в том числе к посетителям Платформы по адресу ${domain}.

Д2. Оператором остаётся ${REQUISITES.legalName} (Республика Беларусь). Обработка ведётся по Закону Республики Беларусь от 7 мая 2021 г. № 99-З «О защите персональных данных» с учётом ${c.dataLaw}.

Д3. Обработка и хранение персональных данных осуществляются на серверах, расположенных в Республике Беларусь. Передача данных ${c.fromCountry} в Республику Беларусь является трансграничной и осуществляется на основании согласия субъекта, которое даётся при отправке формы или при первом входе в личный кабинет. Согласие отзывается в порядке раздела 7 Политики; отзыв согласия влечёт прекращение доступа к Платформе, поскольку без учётной записи услуга технически не оказывается.

Д4. Объём обрабатываемых данных минимален и не зависит от страны: адрес электронной почты и логин ученика, сведения об обучении, а для заявок — имя и контакт, указанные самим заявителем. Работники корпоративных клиентов обезличены — Платформа не получает их персональных данных (раздел 3.3).

Д5. Права субъекта — доступ к сведениям об обработке, изменение, прекращение обработки, отзыв согласия, удаление — реализуются в порядке раздела 7 Политики; дополнительно субъект пользуется правами, предоставленными ${c.dataLaw}. Жалобу на действия Оператора субъект вправе подать в ${c.regulator}.

Д6. Аналитические счётчики подключаются только после отдельного согласия (раздел 8); технически необходимые cookie согласия не требуют.`;
}
