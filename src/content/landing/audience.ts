/**
 * Регистр лендинга: частным лицам («/») и компаниям («/business»).
 *
 * Устроено как в sabak.kz: переключатель — это ССЫЛКИ на разные URL, а не
 * состояние в cookie. Почему так:
 *  • обе версии индексируются, у корпоративной свои (более дорогие) запросы;
 *  • на /business можно лить рекламу и давать ссылку в коммерческом предложении;
 *  • у закупщика ссылка открывает нужную версию сразу, без «переключите вверху».
 *
 * Контент регистров лежит в b2c.ts / b2b.ts и имеет общий тип — поэтому правка
 * структуры страницы автоматически касается обеих версий, а расходиться они
 * могут только там, где это задано данными.
 */

export type Audience = "b2c" | "b2b";

export const AUDIENCES: Audience[] = ["b2c", "b2b"];

/** Куда ведёт переключатель. Главная — частным лицам, /business — компаниям. */
export const AUDIENCE_PATH: Record<Audience, string> = {
  b2c: "/",
  b2b: "/business",
};

/**
 * Подписи регистра. Русские значения остаются дефолтом для серверных мест, где
 * язык не важен; в шапке и на страницах используется словарь i18n/messages.ts —
 * казахская версия переводит их вместе с остальным интерфейсом.
 */
export const AUDIENCE_LABEL: Record<Audience, string> = {
  b2c: "Себе",
  b2b: "Команде",
};

export function otherAudience(current: Audience): Audience {
  return current === "b2c" ? "b2b" : "b2c";
}
