/**
 * Пороги антишаринга. Отдельный модуль без серверных импортов: эти числа нужны
 * и в тексте формы лимита устройств (клиентский компонент), а `heuristics.ts`
 * тянет `node:crypto` и в браузерный бандл не собирается.
 */

/**
 * Сколько устройств разрешено аккаунту: третий вход просто не состоится.
 *
 * Решение владельца (2026-09-08): доступ покупается на одного человека, и двух
 * устройств — телефон и компьютер — на это хватает. Учётка при отказе не
 * страдает: ей ничего не проставляется, человек просто входит с привычного
 * устройства, а неиспользуемое выпадает из счёта через неделю.
 */
export const DEVICE_LIMIT = 2;

/**
 * С какого числа устройств учётка показывается в /admin/flags.
 *
 * При стандартном лимите в два устройства этот сигнал не загорится никогда —
 * больше двух просто не наберётся. Он работает для тех, кому лимит подняли
 * вручную: раздачу пароля там ловить всё ещё нужно, а вход уже не мешает.
 * Основные признаки шаринга при этом другие и от числа устройств не зависят —
 * разные города за короткое окно и объём просмотра больше длительности урока.
 */
export const DEVICE_FLAG_FROM = 3;
