/** Рендер истории диалога для промпта. */
export function renderDialog(messages: { role: "student" | "client"; text: string }[]): string {
  return messages
    .map((m) => `${m.role === "student" ? "Менеджер" : "Клиент"}: ${m.text}`)
    .join("\n");
}
