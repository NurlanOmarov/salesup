/**
 * Заголовок и описание главной для домена и языка. null — своей копии нет
 * (например, казахская версия белорусского домена): вызывающий оставляет то,
 * что уже собрано из общих настроек и словаря языка.
 */
export function countrySeoDefaults(
  countryCode: string | null | undefined,
  locale: Locale = DEFAULT_LOCALE,
): CountryCopy | null {
  const code = SITE_HOSTS.some((s) => s.code === countryCode)
    ? countryCode!
    : DEFAULT_SITE.code;
  return COUNTRY_SEO[code]?.[locale] ?? null;
}

