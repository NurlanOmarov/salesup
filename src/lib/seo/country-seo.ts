/** Заголовок и описание статической страницы для домена; null — своей копии нет. */
export function countryPageSeo(
  path: string,
  countryCode: string | null | undefined,
  locale: Locale = DEFAULT_LOCALE,
): CountryCopy | null {
  if (locale !== DEFAULT_LOCALE) return null;
  const code = SITE_HOSTS.some((s) => s.code === countryCode)
    ? countryCode!
    : DEFAULT_SITE.code;
  return COUNTRY_PAGE_SEO[path]?.[code] ?? null;
}
