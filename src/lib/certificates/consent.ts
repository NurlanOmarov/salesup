import { REQUISITES } from "@/content/legal/requisites";

/**
 * Согласие на обработку персональных данных для сертификата (Закон РБ № 99-З,
 * ст. 5: согласие — свободное, однозначное, информированное, отдельным действием).
 * Даётся на шаге 2 страницы сертификатов галочкой; в Certificate сохраняются
 * время и редакция текста (consentAt, consentVersion) — чтобы по записи можно было
 * восстановить, на что именно согласился человек. Меняете текст — поднимайте версию.
 */
export const CERTIFICATE_CONSENT_VERSION = "cert-1.0";

/** Текст согласия. Работнику организации — с передачей сертификата ответственному. */
export function certificateConsentText(isOrgLearner: boolean): string {
  const recipient = isOrgLearner
    ? "отправки сертификата ответственному представителю организации, которая предоставила мне доступ к курсу"
    : "отправки сертификата на мой адрес электронной почты";
  return (
    `Даю согласие ${REQUISITES.legalNameDative} ` +
    `(УНП ${REQUISITES.unp}) на обработку моих персональных данных — фамилии, имени, отчества, ` +
    `а также сведений о прохождении курса (пройденные уроки, результаты заданий и итогового экзамена) — ` +
    `в целях оформления и выдачи сертификата, ${recipient} и подтверждения подлинности сертификата ` +
    `по его номеру и QR-коду (на странице проверки показываются ФИО, курс, номер и дата выдачи). ` +
    `Согласие действует бессрочно, пока сертификат подлежит проверке, и может быть отозвано ` +
    `заявлением на ${REQUISITES.email}; после отзыва сертификат перестаёт проходить проверку.`
  );
}
