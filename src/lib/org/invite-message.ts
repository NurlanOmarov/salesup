/**
 * Готовый текст, который ответственный пересылает работнику вместе с кодом.
 * Живёт отдельно от компонентов, потому что нужен и при создании кодов, и при
 * повторной отправке из списка выданных.
 *
 * Адрес входа здесь не лишний: со второго раза работник заходит уже не по коду,
 * а по выданному логину, и без ссылки он возвращается на /join.
 */
export function inviteMessage(params: { code: string; siteUrl: string }): string {
  const base = params.siteUrl.replace(/\/$/, "");
  return (
    `Доступ к обучению: откройте ${base}/join, введите код ${params.code}, ` +
    `придумайте пароль. На экране появится ваш логин — сохраните его, ` +
    `по нему вы будете входить дальше на ${base}/login`
  );
}

/** Маска для списка: код виден целиком только по явному клику. */
export function maskInviteCode(code: string): string {
  return `${code.slice(0, 3)}•••${code.slice(-2)}`;
}
