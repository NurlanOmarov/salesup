/**
 * Доступ работнику организации, которого ответственный завёл вручную (без кода
 * самозаписи). Логин здесь — условное обозначение вида acme-0042, а не почта:
 * платформа персональных данных работника не получает.
 *
 * Наименование работодателя стоит в первой же строке: письмо приходит из чата
 * коллеги, и без него текст читается как рассылка неизвестно от кого.
 */
export function orgWorkerWelcomeMessage(params: {
  login: string;
  tempPassword: string;
  siteUrl: string;
  /** Наименование клиента: сотрудник должен понять, от кого пришёл доступ. */
  orgName?: string;
  courses?: string[];
}): string {
  const url = base(params.siteUrl);
  const courses = params.courses?.filter(Boolean) ?? [];
  const org = params.orgName ? ` компании «${params.orgName}»` : "";
  return [
    `Здравствуйте! Направляем информацию для доступа к личному кабинету сотрудника${org} для онлайн-обучения от ACTIVE SALES.`,
    ...(courses.length > 0
      ? ["", courses.length === 1 ? "Ваш курс:" : "Ваши курсы:", ...courses.map((c) => `• ${c}`)]
      : []),
    "",
    "ВХОД",
    `Адрес: ${url}/login`,
    `Логин: ${params.login}`,
    `Временный пароль: ${params.tempPassword}`,
    "",
    "При первом входе система попросит придумать свой постоянный пароль — временный после этого перестанет работать.",
    "",
    "Заниматься можно с телефона, планшета или компьютера — прогресс сохраняется автоматически.",
  ].join("\n");
}

/** Новый временный пароль работнику организации. */
export function orgWorkerPasswordMessage(params: {
  login: string;
  tempPassword: string;
  siteUrl: string;
  orgName?: string;
}): string {
  const url = base(params.siteUrl);
  return [
    params.orgName
      ? `Новый временный пароль для входа в обучение от компании «${params.orgName}».`
      : "Мы выдали новый временный пароль для входа в обучение.",
    "",
    `Адрес: ${url}/login`,
    `Логин: ${params.login}`,
    `Временный пароль: ${params.tempPassword}`,
    "",
    "Старый пароль больше не работает. При входе система попросит придумать новый постоянный пароль.",
  ].join("\n");
}

