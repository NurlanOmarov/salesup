/**
 * Текст, который ответственный пересылает работнику вместе с кодом.
 *
 * Адрес входа здесь не лишний: со второго раза работник заходит уже не по коду,
 * а по выданному логину, и без ссылки он возвращается на /join. По той же
 * причине отдельным пунктом сказано сохранить логин — он показывается один раз
 * на экране после регистрации.
 */
export function inviteMessage(params: { code: string; siteUrl: string }): string {
  const url = base(params.siteUrl);
  return [
    "Здравствуйте! Компания открыла вам доступ к онлайн-обучению ACTIVE SALES.",
    "",
    "ЧТО СДЕЛАТЬ (один раз, займёт минуту)",
    `1. Откройте ${url}/join`,
    `2. Введите код доступа: ${params.code}`,
    "3. Придумайте пароль и запишите его.",
    "4. На экране появится ваш логин — обязательно сохраните его, дальше вход по нему.",
    "",
    `Как входить дальше: ${url}/login — ваш логин и пароль.`,
    "",
    "Код нужен только при первой регистрации. Ни имя, ни почта, ни телефон не запрашиваются. Заниматься можно с телефона, планшета или компьютера — прогресс сохраняется автоматически.",
  ].join("\n");
}
