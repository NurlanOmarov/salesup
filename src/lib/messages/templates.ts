/**
 * Готовые тексты, которыми выдают доступ: владелец — клиенту, ответственный —
 * работнику. Живут отдельно от компонентов по двум причинам.
 *
 * Во-первых, один и тот же текст нужен в нескольких местах (создание учётки и
 * сброс пароля, создание кодов и повторная отправка из списка) — формулировка
 * правится один раз.
 *
 * Во-вторых, доступ передаётся вручную в мессенджере: писем в MVP нет
 * (EMAIL_ENABLED выключен), и качество этого текста — единственное, что стоит
 * между «клиент вошёл» и «клиент написал, что ничего не понял».
 *
 * Формат — простой текст без разметки: сообщения уходят в WhatsApp и Telegram,
 * где ни markdown, ни html не отрендерятся.
 */

/** Убирает хвостовой слэш: адреса собираются конкатенацией. */
function base(siteUrl: string): string {
  return siteUrl.replace(/\/$/, "");
}

/**
 * Первое сообщение ответственному представителю клиента: что такое кабинет
 * организации, как в него войти и что сделать дальше.
 *
 * Намеренно длинное. Человек получает его один раз, до первого входа, и по нему
 * должен пройти весь путь без нашей помощи — включая неочевидное: кабинет
 * компании открывается ссылкой в шапке, а не отдельным адресом.
 */
export function orgAdminWelcomeMessage(params: {
  orgName: string;
  login: string;
  tempPassword: string;
  siteUrl: string;
}): string {
  const url = base(params.siteUrl);
  return [
    `Здравствуйте! Мы создали кабинет организации «${params.orgName}» на платформе ACTIVE SALES.`,
    "",
    "Это кабинет ответственного: из него вы подключаете сотрудников к обучению в рамках оплаченных мест и видите их прогресс.",
    "",
    "ВАШ ДОСТУП",
    `Вход: ${url}/login`,
    `Логин: ${params.login}`,
    `Временный пароль: ${params.tempPassword}`,
    "",
    "При первом входе система попросит придумать постоянный пароль — временный после этого перестанет работать.",
    "",
    "ГДЕ САМ КАБИНЕТ",
    'После входа вы окажетесь на странице «Моё обучение». В меню сверху нажмите «Кабинет компании». Внутри пять разделов:',
    "• Обзор — сколько мест занято и сколько свободно;",
    "• Коды доступа — здесь вы создаёте коды для сотрудников;",
    "• Работники — кто уже подключился;",
    "• Отчёты — прогресс обучения;",
    "• Лицензии — оплаченные курсы и количество мест.",
    "",
    "КАК ПОДКЛЮЧИТЬ СОТРУДНИКА",
    "В разделе «Коды доступа» создайте коды и отправьте каждому сотруднику свой — там же есть кнопка с готовым текстом сообщения. Сотрудник сам придумает пароль и получит логин, место в лицензии займётся автоматически.",
    "",
    "Сотрудники учатся обезличенно: платформа не спрашивает ни ФИО, ни почту, ни телефон — в списке «Работники» они видны как логины вида company-0001. При желании вы можете подписать их именами прямо в кабинете; эти имена шифруются в вашем браузере и нам недоступны.",
    "",
    "Если что-то не получится — напишите нам, поможем.",
  ].join("\n");
}

/**
 * Повторная выдача пароля ответственному (пароль забыт или скомпрометирован).
 * Короткое: про кабинет человек уже знает из первого сообщения.
 */
export function orgAdminPasswordMessage(params: {
  login: string;
  tempPassword: string;
  siteUrl: string;
}): string {
  const url = base(params.siteUrl);
  return [
    "Мы выдали новый временный пароль для входа в кабинет организации.",
    "",
    `Вход: ${url}/login`,
    `Логин: ${params.login}`,
    `Временный пароль: ${params.tempPassword}`,
    "",
    "Старый пароль больше не работает. При входе система попросит придумать новый постоянный пароль.",
  ].join("\n");
}

/**
 * Доступ розничному ученику. Список курсов не обязателен, но с ним сообщение
 * отвечает на первый вопрос человека — «а что мне открыли».
 */
export function studentWelcomeMessage(params: {
  login: string;
  tempPassword: string;
  siteUrl: string;
  courses?: string[];
}): string {
  const url = base(params.siteUrl);
  const courses = params.courses?.filter(Boolean) ?? [];
  return [
    "Здравствуйте! Мы открыли вам доступ к обучению на платформе ACTIVE SALES.",
    ...(courses.length > 0
      ? ["", courses.length === 1 ? "Ваш курс:" : "Ваши курсы:", ...courses.map((c) => `• ${c}`)]
      : []),
    "",
    "ВХОД",
    `Адрес: ${url}/login`,
    `Логин: ${params.login}`,
    `Временный пароль: ${params.tempPassword}`,
    "",
    "При первом входе система попросит придумать свой постоянный пароль — временный после этого перестанет работать.",
    "",
    "Заниматься можно с телефона, планшета или компьютера — прогресс сохраняется автоматически, продолжите с того места, где остановились.",
  ].join("\n");
}

