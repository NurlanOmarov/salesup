-- Канал связи в заявке. Раньше контакт был одной строкой «как оставил человек»:
-- приходили заявки с одной почтой, по которой отвечают долго, хотя можно было
-- написать в мессенджер. Теперь канал выбирается явно, а номер хранится в E.164.
CREATE TYPE "LeadContactType" AS ENUM ('WHATSAPP', 'TELEGRAM', 'VIBER', 'EMAIL');

ALTER TABLE "Lead" ADD COLUMN "contactType" "LeadContactType";
-- Страна номера (ISO): она не обязана совпадать с доменом заявки — на белорусскую
-- витрину заходят с казахстанским номером, и владельцу это видно до звонка.
ALTER TABLE "Lead" ADD COLUMN "contactCountry" TEXT;
