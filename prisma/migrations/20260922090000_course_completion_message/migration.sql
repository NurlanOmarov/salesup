-- Благодарность по окончании курса (Course.completionMessage).
-- «Продажи в DIY-магазине» — первая часть основного курса, который ещё не вышел:
-- по окончании ученику говорим спасибо и обещаем основную часть. Значение
-- продублировано в prisma/seed.ts, правится в админке курса.
ALTER TABLE "Course" ADD COLUMN "completionMessage" TEXT;

UPDATE "Course"
SET "completionMessage" = 'Вы завершили первую часть большого курса по продажам в DIY-рознице. Основная часть уже готовится — в ней будет ещё больше техник и практики. Следите за новостями: мы сообщим, как только она выйдет.'
WHERE slug = 'sales-diy';
