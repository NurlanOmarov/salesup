-- Окончательные цены курсов (docs/PRICING-PLAN.md, редакция 2 от 2026-08-14).
--
-- Цена определяется классом курса — той же осью, что и витрина (Course.audience):
--   SPECIALIZED (отраслевой: туризм, кухни, обувь, недвижимость, медпреды, B2B) → 490 BYN
--   EVERYONE    (общая тема: тайм-менеджмент, СПИН, переговоры)                 → 320 BYN
--
-- Обоснование: собственный каталог activesales.by/shop продаёт отраслевой видеокурс
-- без интерактива по 300–400 BYN. Новый продукт берёт премию +30–60 % за AI-наставника,
-- тренажёры и верифицируемый сертификат, оставаясь заметно ниже «профессий» брендовых
-- платформ (Skillbox-эквивалент ≈ 750 BYN).
--
-- Поле priceTiyn хранит BYN-копейки (историческое имя, см. D-010): 490 BYN = 49000.
--
-- ВАЖНО: до этой миграции значения в prisma/seed.ts и в проде разошлись на порядок —
-- seed создавал курсы по 300 000 tiyn (3 000 BYN), тогда как миграция
-- 20260719120000_course_price_base_kzt_to_byn пересчитала прод в 30 000 tiyn (300 BYN).
-- Эта миграция устраняет расхождение: и там, и там теперь одно число.

UPDATE "Course"
SET "priceTiyn" = CASE "audience"
    WHEN 'EVERYONE' THEN 32000
    ELSE 49000
  END;

-- Старые «зачёркнутые» цены обнуляем: после перехода на новую сетку они стали
-- бессмысленными (у части курсов oldPrice оказался НИЖЕ новой цены), а показывать
-- перечёркнутую цену, по которой никто не покупал, — то самое, за что критикуют
-- оферты Skillbox и GeekBrains. Промо-механика вводится отдельным решением
-- с реальным сроком действия (PRICING-PLAN §7).
UPDATE "Course"
SET "oldPriceTiyn" = NULL
WHERE "oldPriceTiyn" IS NOT NULL;
