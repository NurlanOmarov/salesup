-- Срок доступа курса по умолчанию: год вместо «бессрочно» (docs/PRICING-PLAN.md §9).
--
-- Поле задаёт, что получит ученик, когда админ оставляет «по тарифу курса».
-- Стояло значение по умолчанию из схемы — LIFETIME, — то есть каждый ученик
-- получал пожизненный доступ, хотя тарифная политика обещает год: материалы
-- остаются у ученика навсегда, но AI-наставник и тренажёры тратят токены, и
-- бессрочный доступ к ним — это бессрочное обязательство по расходам.
--
-- Меняем только там, где стоит LIFETIME: если владелец осознанно выставил курсу
-- другой срок, его решение не трогаем. Уже выданные доступы тоже не трогаем —
-- срок записан в самой записи о зачислении, и сокращать его задним числом нечестно.

ALTER TABLE "Course" ALTER COLUMN "accessDuration" SET DEFAULT 'MONTHS_12';

UPDATE "Course"
SET "accessDuration" = 'MONTHS_12'
WHERE "accessDuration" = 'LIFETIME';
